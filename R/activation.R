# ------------------------------------------------------------------------------
# Activation conditions for parameters
#
# Some parameters only have an effect when another parameter takes a particular
# value (e.g. an engine-specific argument). An activation condition is an
# expression that references other parameter identifiers and evaluates to a
# single logical value. Conditions are honored while candidates are generated:
# parameters are processed in dependency order and inactive cells receive an
# explicit sentinel instead of a value. This is distinct from `filter`, which
# only removes fully generated rows after the fact.
# ------------------------------------------------------------------------------

#' Declare parameter activation conditions
#'
#' @description
#' Some tuning parameters only have an effect when another parameter takes a
#' particular value. For example, a model argument may only be used by one
#' engine. `activate()` records, on a [parameters()] set, the condition under
#' which each parameter is active. The condition is then honored while grids
#' are generated by [grid_regular()], [grid_random()], and [grid_hybrid()]:
#' parameters are processed in dependency order and cells where the condition is
#' not satisfied receive an explicit `NA` sentinel rather than a value.
#'
#' Activation conditions are part of candidate _generation_, not row filtering:
#' inactive parameters never take part in the Cartesian expansion, so no
#' meaningless placeholder combinations are created (and duplicates cannot
#' differ only in their inactive cells). The `filter` argument of the grid
#' functions remains available for filtering the resulting rows.
#'
#' @param .x A [parameters()] object.
#'
#' @param ... Named expressions. The name must match the `id` of a parameter in
#' `.x` and the expression must reference one or more other parameter
#' identifiers and evaluate to a single `TRUE` or `FALSE`. A parameter can only
#' be given one activation condition; calling `activate()` again replaces any
#' previously declared condition for the named parameter.
#'
#' @param .strict A logical. Should the condition be checked against the
#' parameter's possible values immediately, rejecting conditions that can never
#' be satisfied? Defaults to `TRUE`.
#'
#' @return
#' A [parameters()] object with an additional `activation` list-column holding
#' the activation expressions (as quosures); `NULL` entries mark parameters
#' that are always active.
#'
#' @examples
#' pset <- parameters(list(
#'   prune = prune_method(c("backward", "none", "cost")),
#'   trees = trees()
#' ))
#' pset <- activate(pset, trees = prune == "cost")
#' pset
#'
#' grid_regular(pset, levels = 3)
#'
#' deactivate(pset, trees)
#'
#' @name activate
#' @export
activate <- function(.x, ..., .strict = TRUE) {
  UseMethod("activate")
}

#' @export
#' @rdname activate
activate.parameters <- function(.x, ..., .strict = TRUE) {
  check_bool(.strict)
  cond_quos <- enquos(...)
  x_ids <- .x$id

  if (length(cond_quos) == 0L) {
    cli::cli_abort(
      "At least one activation condition must be supplied to {.fn activate}."
    )
  }
  cond_names <- names(cond_quos)
  if (is.null(cond_names) || any(cond_names == "" | is.na(cond_names))) {
    cli::cli_abort(
      "Every activation condition must be named with a parameter {.arg id}."
    )
  }
  check_unique(cond_names, arg = "activation condition names")

  unknown <- setdiff(cond_names, .x$id)
  if (length(unknown) > 0L) {
    cli::cli_abort(
      c(
        "Activation condition{?s} reference{?s/} parameter{?s} not in the set:
        {.val {unknown}}.",
        i = "Parameter identifiers available: {.val {x_ids}}."
      )
    )
  }

  activation <- activation_col(.x)

  for (nm in cond_names) {
    quo <- cond_quos[[nm]]
    refs <- quo_referenced_ids(quo)
    bad_refs <- setdiff(refs, .x$id)
    if (length(bad_refs) > 0L) {
      cli::cli_abort(
        c(
          "The activation condition for {.val {nm}} references unknown
          parameter{?s}: {.val {bad_refs}}.",
          i = "Parameter identifiers available: {.val {x_ids}}."
        )
      )
    }
    if (nm %in% refs) {
      cli::cli_abort(
        "The activation condition for {.val {nm}} cannot reference {.val {nm}}
        itself."
      )
    }
    if (length(refs) == 0L) {
      cli::cli_abort(
        "The activation condition for {.val {nm}} must reference at least one
        other parameter."
      )
    }
    activation[[which(.x$id == nm)]] <- quo
  }

  # Structural validation: dependency graph must be acyclic. This also rejects
  # self references that survived the check above.
  plan <- activation_plan(.x$id, activation)

  if (.strict) {
    check_activation_satisfiable(.x, activation, plan)
  }

  .x$activation <- activation
  .x
}

#' @export
#' @rdname activate
activate.default <- function(.x, ..., .strict = TRUE) {
  x_obj <- .x
  cli::cli_abort(
    "{.fn activate} requires a {.cls parameters} object, not
    {.obj_type_friendly {x_obj}}."
  )
}

#' @param ids <[`tidy-select`][tidyselect::language]> In `deactivate()`, the
#' parameter identifiers whose activation conditions should be removed,
#' selected as in [grid_hybrid()]. If `NULL` (the default), all activation
#' conditions are removed.
#'
#' @rdname activate
#' @export
deactivate <- function(.x, ids = NULL, ...) {
  UseMethod("deactivate")
}

#' @export
#' @rdname activate
deactivate.parameters <- function(.x, ids = NULL, ...) {
  check_dots_empty()
  id_quo <- enquo(ids)
  activation <- activation_col(.x)
  x_ids <- .x$id

  if (quo_is_null(id_quo)) {
    activation <- rep(list(NULL), length(activation))
    .x$activation <- activation
    return(.x)
  }

  selected <- try_fetch(
    tidyselect::eval_select(
      id_quo,
      data = set_names(x_ids),
      allow_rename = FALSE
    ),
    vctrs_error_subscript_oob = function(cnd) {
      cli::cli_abort(
        "{.arg ids} contains {.val {cnd$i}}, which {?is/are} not among the
        parameter identifiers: {.val {x_ids}}."
      )
    },
    error = function(cnd) {
      cli::cli_abort(
        "{.arg ids} must reference parameter identifiers in the set:
        {.val {x_ids}}."
      )
    }
  )
  activation[as.integer(selected)] <- list(NULL)
  .x$activation <- activation
  .x
}

#' @export
#' @rdname activate
deactivate.default <- function(.x, ids = NULL, ...) {
  x_obj <- .x
  cli::cli_abort(
    "{.fn deactivate} requires a {.cls parameters} object, not
    {.obj_type_friendly {x_obj}}."
  )
}

