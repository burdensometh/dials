# Append a parameter column to an in-progress grid data frame, honoring its
# activation condition. Inactive rows receive the explicit sentinel; active
# rows are expanded (regular) or sampled (random).
#
# `mode` is "regular" (with `levels`) or "random" (with `size`).
append_activated_column <- function(
  grid,
  id,
  param,
  quo,
  mode,
  levels = NULL,
  size = NULL,
  original = TRUE,
  call = caller_env()
) {
  if (nrow(grid) == 0L) {
    grid[[id]] <- inactive_value(param)[0L]
    return(grid)
  }

  if (is.null(quo)) {
    active <- rep(TRUE, nrow(grid))
  } else {
    active <- eval_activation(quo, grid, id, call = call)
  }

  sentinel <- inactive_value(param)
  column <- rep(sentinel, nrow(grid))

  if (!any(active)) {
    grid[[id]] <- column
    return(grid)
  }

  active_idx <- which(active)
  if (mode == "regular") {
    vals <- value_seq(param, n = levels, original = original)
    # Each active partial combination is expanded over every value.
    expanded <- lapply(active_idx, function(i) {
      row <- grid[rep(i, length(vals)), , drop = FALSE]
      row[[id]] <- vals
      row
    })
    inactive <- grid[!active, , drop = FALSE]
    if (nrow(inactive) > 0L) {
      inactive[[id]] <- rep(sentinel, nrow(inactive))
      expanded <- c(expanded, list(inactive))
    }
    out <- vec_rbind(!!!expanded)
    # Stable order: active rows first (in original row order), inactive last.
    return(out)
  }

  # Random mode: one sampled value per active row. Inactive rows keep the
  # shared sentinel so that deduplication cannot treat placeholders as distinct
  # candidates.
  vals <- value_sample(param, n = sum(active), original = original)
  column[active] <- vals
  grid[[id]] <- column
  grid
}

# Regular grid honoring an activation plan. Replaces a plain
# expand.grid() Cartesian product.
make_activated_regular_grid <- function(
  params,
  ids,
  plan,
  levels,
  original = TRUE,
  call = caller_env()
) {
  # Start with a single anonymous partial combination so that the first
  # parameter has something to expand against.
  grid <- new_data_frame(list(dials_activation_seed = NA), n = 1L)
  for (i in plan$order) {
    grid <- append_activated_column(
      grid,
      id = ids[[i]],
      param = params[[i]],
      quo = plan$activation[[i]],
      mode = "regular",
      levels = levels[[i]],
      original = original,
      call = call
    )
  }
  grid[, ids, drop = FALSE]
}

# Random grid honoring an activation plan. Inactive cells are filled with the
# sentinel before deduplication, so duplicates cannot differ only in inactive
# cells.
make_activated_random_grid <- function(
  params,
  ids,
  plan,
  size,
  original = TRUE,
  call = caller_env()
) {
  # Start with `size` anonymous partial combinations so that each parameter
  # column independently draws one value per row, mirroring grid_random().
  grid <- new_data_frame(
    list(dials_activation_seed = rep(NA_integer_, size)),
    n = as.integer(size)
  )
  for (i in plan$order) {
    grid <- append_activated_column(
      grid,
      id = ids[[i]],
      param = params[[i]],
      quo = plan$activation[[i]],
      mode = "random",
      size = size,
      original = original,
      call = call
    )
  }
  grid[, ids, drop = FALSE]
}

# Apply activation conditions to an already generated (e.g. crossed hybrid)
# grid. Conditions are evaluated in dependency order and inactive cells are
# overwritten with the sentinel.
apply_activation_to_grid <- function(
  grid,
  params,
  ids,
  plan,
  call = caller_env()
) {
  for (i in plan$order) {
    quo <- plan$activation[[i]]
    if (is.null(quo)) {
      next
    }
    active <- eval_activation(quo, grid, ids[[i]], call = call)
    grid[[ids[[i]]]][!active] <- inactive_value(params[[i]])
  }
  grid[, ids, drop = FALSE]
}
