# Retrieve the activation list-column, tolerating parameters objects built by
# older code that did not include it.
activation_col <- function(x) {
  if (rlang::has_name(x, "activation")) {
    res <- x$activation
  } else {
    res <- rep(list(NULL), nrow(x))
  }
  if (is.null(res)) {
    res <- rep(list(NULL), nrow(x))
  }
  res
}

# Whether a parameters set declares at least one activation condition.
has_activation <- function(x) {
  any(map_lgl(activation_col(x), function(elt) !is.null(elt)))
}

# Return a parameters set with every activation condition removed. Used when a
# subset of the parameters is generated independently (e.g. inside
# grid_hybrid()); the parent set re-applies the full plan afterwards.
strip_activation <- function(x) {
  x$activation <- rep(list(NULL), nrow(x))
  x
}

# Names referenced by a condition expression.
quo_referenced_ids <- function(quo) {
  expr <- quo_get_expr(quo)
  if (is.null(expr)) {
    return(character(0))
  }
  all.names(expr, functions = FALSE, unique = TRUE)
}

#' Build and validate an activation plan
#'
#' Returns a list with:
#' * `order`: parameter indices in dependency order (a topological sort, with
#'   parameters without conditions keeping their relative position);
#' * `activation`: the activation list aligned with `ids`.
#'
#' Rejects unknown references and dependency cycles before any candidate is
#' generated.
#'
#' @noRd
activation_plan <- function(ids, activation, call = caller_env()) {
  if (is.null(activation)) {
    activation <- rep(list(NULL), length(ids))
  }
  n <- length(ids)
  if (length(activation) != n) {
    cli::cli_abort(
      "The activation conditions must have the same length as the parameter
      set.",
      .internal = TRUE, call = call
    )
  }

  # Edge j -> i when i's condition references j: j must be processed first.
  adjacency <- vector("list", n)
  indegree <- integer(n)
  for (i in seq_len(n)) {
    quo <- activation[[i]]
    if (is.null(quo)) {
      next
    }
    refs <- quo_referenced_ids(quo)
    bad <- setdiff(refs, ids)
    if (length(bad) > 0L) {
      cli::cli_abort(
        c(
          "The activation condition for {.val {ids[[i]]}} references unknown
          parameter{?s}: {.val {bad}}.",
          i = "Parameter identifiers available: {.val {ids}}."
        ),
        call = call
      )
    }
    ref_idx <- match(refs, ids)
    if (i %in% ref_idx) {
      cli::cli_abort(
        "The activation condition for {.val {ids[[i]]}} cannot reference
        {.val {ids[[i]]}} itself.",
        call = call
      )
    }
    adjacency[[i]] <- ref_idx
    indegree[i] <- length(unique(ref_idx))
  }

  # Kahn's algorithm. Candidates without incoming edges keep original relative
  # order, so unconditional parameters naturally stay in place where possible.
  ready <- which(indegree == 0L)
  order <- integer(0)
  while (length(ready) > 0L) {
    i <- ready[[1L]]
    ready <- ready[-1L]
    order <- c(order, i)
    dependents <- which(map_lgl(adjacency, function(refs) i %in% refs))
    for (d in dependents) {
      indegree[d] <- indegree[d] - 1L
      if (indegree[d] == 0L) {
        ready <- c(ready, d)
      }
    }
  }

  if (length(order) != n) {
    cycle <- ids[setdiff(seq_len(n), order)]
    cli::cli_abort(
      c(
        "Activation conditions contain a dependency cycle; parameters must be
        processable in dependency order.",
        x = "Parameters involved in the cycle: {.val {cycle}}."
      ),
      call = call
    )
  }

  list(order = order, activation = activation)
}

# Evaluate an activation condition against a data frame of already generated
# columns. Returns a logical vector; missing values are treated as inactive.
eval_activation <- function(quo, data, id, call = caller_env()) {
  res <- try_fetch(
    rlang::eval_tidy(quo, data = data),
    error = function(cnd) {
      cli::cli_abort(
        "The activation condition for {.val {id}} could not be evaluated:
        {conditionMessage(cnd)}.",
        parent = cnd, call = call
      )
    }
  )
  if (!is.logical(res)) {
    cli::cli_abort(
      "The activation condition for {.val {id}} must evaluate to a logical
      vector, not {.obj_type_friendly {res}}.",
      call = call
    )
  }
  if (length(res) == 1L) {
    res <- rep(res, nrow(data))
  }
  if (length(res) != nrow(data)) {
    cli::cli_abort(
      "The activation condition for {.val {id}} must evaluate to a single
      logical value or one logical value per candidate ({nrow(data)}), not
      {length(res)} value{?s}.",
      call = call
    )
  }
  # A condition on an inactive (NA) upstream parameter cannot be satisfied.
  res[is.na(res)] <- FALSE
  res
}

# Explicit sentinel for an inactive parameter cell. The sentinel matches the
# parameter's value type so the grid column remains type-consistent.
inactive_value <- function(param) {
  switch(
    param$type,
    double = NA_real_,
    integer = NA_integer_,
    character = NA_character_,
    logical = NA,
    NA
  )
}

# Reject conditions that can never be satisfied given the possible values of
# the parameters they reference ("conflicting conditions").
check_activation_satisfiable <- function(
  x,
  activation,
  plan,
  call = caller_env()
) {
  ids <- x$id
  for (i in seq_len(nrow(x))) {
    quo <- activation[[i]]
    if (is.null(quo)) {
      next
    }
    refs <- quo_referenced_ids(quo)
    ref_objs <- x$object[match(refs, ids)]
    if (any(map_lgl(ref_objs, function(obj) !inherits(obj, "param")))) {
      next
    }
    # Satisfiability cannot be decided for parameters whose ranges or values
    # are not yet finalized; grid generation itself rejects unknowns later.
    if (any(map_lgl(ref_objs, has_unknowns))) {
      next
    }
    # A small regular grid over every referenced parameter is enough to decide
    # whether the condition is ever TRUE. The Cartesian product is capped so
    # that conditions referencing several quantitative parameters stay cheap.
    probe_vals <- set_names(
      map(ref_objs, probe_values),
      refs
    )
    probe <- probe_grid(probe_vals, ref_objs)
    vals <- try_fetch(
      rlang::eval_tidy(quo, data = probe),
      error = function(cnd) {
        cli::cli_abort(
          "The activation condition for {.val {ids[[i]]}} could not be
          evaluated: {conditionMessage(cnd)}.",
          parent = cnd, call = call
        )
      }
    )
    if (!is.logical(vals)) {
      cli::cli_abort(
        "The activation condition for {.val {ids[[i]]}} must evaluate to a
        logical vector, not {.obj_type_friendly {vals}}.",
        call = call
      )
    }
    if (!any(vals, na.rm = TRUE)) {
      cli::cli_abort(
        c(
          "The activation condition for {.val {ids[[i]]}} can never be
          satisfied given the possible values of the parameters it references.",
          i = "Check the condition and the referenced parameter values."
        ),
        call = call
      )
    }
  }
  invisible(NULL)
}

# A compact set of values used to probe satisfiability; capped to keep the
# probe grid small.
probe_values <- function(param, n = 5L) {
  vals <- try_fetch(
    value_seq(param, n = n, original = TRUE),
    error = function(cnd) {
      if (!is.null(param$values)) {
        utils::head(param$values, n)
      } else {
        c(param$range$lower, param$range$upper)
      }
    }
  )
  unique(vals)
}

# Cartesian probe grid with a bounded number of rows. Qualitative parameters
# keep all of their (typically few) values so that equality conditions cannot
# be declared unsatisfiable because a level was trimmed; quantitative
# parameters are trimmed to roughly the same number of values when the product
# exceeds the cap.
probe_grid <- function(vals, params, cap = 200L) {
  sizes <- lengths(vals)
  if (prod(sizes) > cap) {
    quant <- map_lgl(params, inherits, "quant_param")
    fixed_prod <- prod(sizes[!quant])
    if (fixed_prod >= cap) {
      # Many qualitative combinations: keep all levels anyway, accepting a
      # larger probe grid rather than risking a false conflict.
      return(as_tibble(expand.grid(vals, stringsAsFactors = FALSE)))
    }
    n_quant <- max(1L, sum(quant))
    per <- max(2L, floor((cap / fixed_prod)^(1 / n_quant)))
    vals[quant] <- map(
      vals[quant],
      function(x) utils::head(x, min(per, length(x)))
    )
  }
  as_tibble(expand.grid(vals, stringsAsFactors = FALSE))
}

